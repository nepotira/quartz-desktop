//! # Accents Character Picker Daemon (`qz-daemons::input_helpers::accents`)
//!
//! Production-grade press-and-hold diacritics picker matching the canonical macOS Tahoe 26
//! character selection popover.
//!
//! ### Operating Behavior:
//! - When a letter key is held down for more than 300ms (`press_and_hold_threshold`), standard
//!   keyboard repeat is suppressed.
//! - A floating glass popover appears above the text cursor presenting numbered diacritic
//!   alternatives (e.g. holding `e` reveals `1: é, 2: è, 3: ê, 4: ë, 5: ē, 6: ė, 7: ę`).
//! - Pressing the corresponding number digit (1–9) or pressing Enter/Space on the highlighted
//!   candidate commits that character and dismisses the popover.
//! - Pressing Escape or typing another character cancels the popover without commit.

use glam::Vec2;
use serde::{Deserialize, Serialize};

/// Action generated by the Accents state machine.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub enum AccentsAction {
    /// No action required; normal typing continues.
    None,
    /// Press-and-hold threshold reached; show diacritic picker popover.
    ShowPicker {
        /// Base character that was held down.
        base_char: char,
        /// List of diacritic candidates for selection.
        candidates: Vec<char>,
        /// Cursor coordinates `[x, y]` where popover should anchor.
        cursor_position: [i32; 2],
    },
    /// A diacritic was selected and should be committed into the active input client.
    CommitCharacter(char),
    /// Picker was dismissed without selection.
    Dismiss,
}

/// State of the press-and-hold accents engine.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub enum AccentsState {
    /// Idle state waiting for key press.
    Idle,
    /// Key is held down, tracking duration until threshold.
    PendingHold {
        /// Key being held.
        key: char,
        /// Time in seconds key has been held down.
        elapsed_seconds: f64,
        /// Screen position of text cursor.
        cursor_pos: Vec2,
    },
    /// Picker is actively displayed on screen.
    ActivePicker {
        /// Base character.
        base_char: char,
        /// Diacritic alternatives.
        candidates: Vec<char>,
        /// Currently highlighted candidate index (0-indexed).
        selected_index: usize,
        /// Screen position of text cursor.
        cursor_pos: Vec2,
    },
}

/// Accents Character Picker Manager.
#[derive(Debug, Clone)]
pub struct AccentsManager {
    /// Current state machine status.
    state: AccentsState,
    /// Duration in seconds required to trigger the diacritic popover (macOS standard: 0.300s).
    pub hold_threshold_seconds: f64,
}

impl Default for AccentsManager {
    fn default() -> Self {
        Self::new()
    }
}

impl AccentsManager {
    /// Canonical macOS Tahoe 26 press-and-hold threshold in seconds ($0.400\text{s} = 400\text{ms}$, Pillar 13).
    pub const HOLD_THRESHOLD_TAHOE_SECS: f64 = 0.40;

    /// Creates a new `AccentsManager` with standard threshold.
    #[must_use]
    pub fn new() -> Self {
        Self {
            state: AccentsState::Idle,
            hold_threshold_seconds: 0.30,
        }
    }

    /// Creates a new `AccentsManager` configured with the strict macOS Tahoe 26 $400\text{ms}$ threshold.
    #[must_use]
    pub fn new_tahoe_400ms() -> Self {
        Self {
            state: AccentsState::Idle,
            hold_threshold_seconds: Self::HOLD_THRESHOLD_TAHOE_SECS,
        }
    }

    /// Returns candidate diacritics for a given character, preserving casing.
    #[must_use]
    pub fn get_candidates(c: char) -> Option<Vec<char>> {
        let is_upper = c.is_uppercase();
        let lower = c.to_ascii_lowercase();

        let base_candidates: &[char] = match lower {
            'a' => &['á', 'à', 'â', 'ä', 'æ', 'ã', 'å', 'ā'],
            'c' => &['ç', 'ć', 'č'],
            'e' => &['é', 'è', 'ê', 'ë', 'ē', 'ė', 'ę'],
            'i' => &['í', 'ì', 'î', 'ï', 'ī', 'į'],
            'l' => &['ł'],
            'n' => &['ñ', 'ń'],
            'o' => &['ó', 'ò', 'ô', 'ö', 'õ', 'ø', 'ō', 'œ'],
            's' => &['ß', 'ś', 'š'],
            'u' => &['ú', 'ù', 'û', 'ü', 'ū'],
            'y' => &['ÿ', 'ý'],
            'z' => &['ž', 'ź', 'ż'],
            _ => return None,
        };

        if is_upper {
            Some(
                base_candidates
                    .iter()
                    .map(|&ch| {
                        let mut s = ch.to_uppercase();
                        s.next().unwrap_or(ch)
                    })
                    .collect(),
            )
        } else {
            Some(base_candidates.to_vec())
        }
    }

    /// Handles a key-down event from the compositor input pipeline.
    pub fn handle_key_down(&mut self, key: char, cursor_pos: Vec2) -> AccentsAction {
        match &mut self.state {
            AccentsState::Idle => {
                if Self::get_candidates(key).is_some() {
                    self.state = AccentsState::PendingHold {
                        key,
                        elapsed_seconds: 0.0,
                        cursor_pos,
                    };
                }
                AccentsAction::None
            }
            AccentsState::PendingHold { key: prev_key, .. } => {
                if *prev_key != key {
                    // New key pressed before hold triggered -> cancel previous hold
                    if Self::get_candidates(key).is_some() {
                        self.state = AccentsState::PendingHold {
                            key,
                            elapsed_seconds: 0.0,
                            cursor_pos,
                        };
                    } else {
                        self.state = AccentsState::Idle;
                    }
                }
                AccentsAction::None
            }
            AccentsState::ActivePicker { candidates, selected_index, .. } => {
                // If a digit 1..9 is pressed, commit the corresponding candidate!
                if let Some(digit) = key.to_digit(10) {
                    if digit >= 1 && (digit as usize) <= candidates.len() {
                        let chosen = candidates[(digit - 1) as usize];
                        self.state = AccentsState::Idle;
                        return AccentsAction::CommitCharacter(chosen);
                    }
                }

                // If Enter or Space is pressed, commit the currently highlighted candidate
                if key == '\n' || key == ' ' {
                    let chosen = candidates[*selected_index];
                    self.state = AccentsState::Idle;
                    return AccentsAction::CommitCharacter(chosen);
                }

                // If Escape is pressed, dismiss
                if key == '\u{1b}' {
                    self.state = AccentsState::Idle;
                    return AccentsAction::Dismiss;
                }

                // Any other key typing dismisses the popover
                self.state = AccentsState::Idle;
                AccentsAction::Dismiss
            }
        }
    }

    /// Advances elapsed hold time by `dt` seconds.
    pub fn tick(&mut self, dt: f64) -> AccentsAction {
        if let AccentsState::PendingHold { key, elapsed_seconds, cursor_pos } = &mut self.state {
            *elapsed_seconds += dt;
            if *elapsed_seconds >= self.hold_threshold_seconds {
                if let Some(candidates) = Self::get_candidates(*key) {
                    let k = *key;
                    let c_pos = *cursor_pos;
                    self.state = AccentsState::ActivePicker {
                        base_char: k,
                        candidates: candidates.clone(),
                        selected_index: 0,
                        cursor_pos: c_pos,
                    };
                    return AccentsAction::ShowPicker {
                        base_char: k,
                        candidates,
                        cursor_position: [c_pos.x as i32, c_pos.y as i32],
                    };
                } else {
                    self.state = AccentsState::Idle;
                }
            }
        }
        AccentsAction::None
    }

    /// Handles arrow navigation when picker is active.
    pub fn handle_navigation(&mut self, delta: i32) {
        if let AccentsState::ActivePicker { candidates, selected_index, .. } = &mut self.state {
            let total = candidates.len() as i32;
            let current = *selected_index as i32;
            let new_idx = (current + delta).rem_euclid(total);
            *selected_index = new_idx as usize;
        }
    }

    /// Handles a key-up event.
    pub fn handle_key_up(&mut self, key: char) {
        if let AccentsState::PendingHold { key: hold_key, .. } = self.state {
            if hold_key == key {
                // Key was released before 300ms threshold -> back to idle
                self.state = AccentsState::Idle;
            }
        }
    }

    /// Commits candidate at specified 0-based index directly (e.g. from mouse click).
    pub fn select_index(&mut self, index: usize) -> Option<AccentsAction> {
        if let AccentsState::ActivePicker { candidates, .. } = &self.state {
            if index < candidates.len() {
                let chosen = candidates[index];
                self.state = AccentsState::Idle;
                return Some(AccentsAction::CommitCharacter(chosen));
            }
        }
        None
    }

    /// Returns current state.
    #[must_use]
    pub fn state(&self) -> &AccentsState {
        &self.state
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_candidate_generation() {
        let e_candidates = AccentsManager::get_candidates('e').unwrap();
        assert_eq!(e_candidates, vec!['é', 'è', 'ê', 'ë', 'ē', 'ė', 'ę']);

        let upper_e = AccentsManager::get_candidates('E').unwrap();
        assert_eq!(upper_e, vec!['É', 'È', 'Ê', 'Ë', 'Ē', 'Ė', 'Ę']);

        assert!(AccentsManager::get_candidates('x').is_none());
    }

    #[test]
    fn test_hold_threshold_activation_and_digit_commit() {
        let mut manager = AccentsManager::new();
        let cursor = Vec2::new(200.0, 300.0);

        // Key down on 'e'
        let act = manager.handle_key_down('e', cursor);
        assert_eq!(act, AccentsAction::None);

        // Advance 0.1s -> still pending
        let act = manager.tick(0.10);
        assert_eq!(act, AccentsAction::None);

        // Advance 0.25s (total 0.35s > 0.30s threshold) -> ShowPicker
        let act = manager.tick(0.25);
        match act {
            AccentsAction::ShowPicker { base_char, candidates, cursor_position } => {
                assert_eq!(base_char, 'e');
                assert_eq!(candidates.len(), 7);
                assert_eq!(cursor_position, [200, 300]);
            }
            _ => panic!("Expected ShowPicker action"),
        }

        // Typing digit '1' should commit 'é'
        let act = manager.handle_key_down('1', cursor);
        assert_eq!(act, AccentsAction::CommitCharacter('é'));
        assert_eq!(manager.state(), &AccentsState::Idle);
    }

    #[test]
    fn test_early_release_cancels_hold() {
        let mut manager = AccentsManager::new();
        manager.handle_key_down('a', Vec2::ZERO);
        manager.tick(0.15); // Halfway
        manager.handle_key_up('a');

        assert_eq!(manager.state(), &AccentsState::Idle);
        // Ticking further should do nothing
        let act = manager.tick(0.25);
        assert_eq!(act, AccentsAction::None);
    }

    #[test]
    fn test_navigation_and_enter_commit() {
        let mut manager = AccentsManager::new();
        manager.handle_key_down('c', Vec2::ZERO);
        manager.tick(0.35); // Trigger picker: ['ç', 'ć', 'č']

        // Navigate right by 1 -> index 1 ('ć')
        manager.handle_navigation(1);
        let act = manager.handle_key_down('\n', Vec2::ZERO);
        assert_eq!(act, AccentsAction::CommitCharacter('ć'));
    }
}
